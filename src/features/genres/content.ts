export function getEditorialArtistFallbacks(
  content: GenreEditorialContent,
  artistProfiles: {
    id: string;
    name: string;
    image_url_thumb: string | null;
    image_url_large: string | null;
    primary_macro: string | null;
  }[] = [],
): { pillars: GenreArtist[]; examples: GenreArtist[] } {
  const normalizeArtist = (name: string) =>
    name
      .normalize('NFD')
      .replace(/[\u0300-\u036f]/g, '')
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, ' ')
      .trim()
      .replace(/\s+/g, ' ');
  const profilesByName = new Map<string, (typeof artistProfiles)[number]>();
  for (const profile of artistProfiles) {
    const normalized = normalizeArtist(profile.name);
    if (normalized) profilesByName.set(normalized, profile);
    const withoutThe = normalized.replace(/^the\s+/, '');
    if (withoutThe) profilesByName.set(withoutThe, profile);
  }

  const mapArtists = (
    kind: 'pillar' | 'example',
    artists: GenreArtistContent[],
  ): GenreArtist[] => {
    return artists.map((artist, index) => {
      const normalized = normalizeArtist(artist.name);
      const profile =
        profilesByName.get(normalized) ??
        profilesByName.get(normalized.replace(/^the\s+/, ''));
      return {
        id: profile?.id ?? `editorial-${content.slug}-${kind}-${index + 1}`,
        name: profile?.name ?? artist.name,
        image_url_thumb: profile?.image_url_thumb ?? null,
        image_url_large: profile?.image_url_large ?? null,
        primary_macro: profile?.primary_macro ?? content.slug,
        position: index + 1,
        why: artist.why,
        note: artist.note ?? null,
        seen_count: 0,
        in_wishlist: false,
        isEditorialFallback: true,
        isArtistLinked: Boolean(profile),
      };
    });
  };

  return {
    pillars: mapArtists('pillar', content.pillars),
    examples: mapArtists('example', content.examples),
  };
}

function normalizeArtistLookupName(value: string): string {
  return value
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, ' ')
    .trim()
    .replace(/\s+/g, ' ');
}

function mergeEditorialArtists(
  editorialArtists: GenreArtist[],
  seededArtists: GenreArtist[],
): GenreArtist[] {
  const seededByName = new Map(
    seededArtists.flatMap((artist) => {
      const normalized = normalizeArtistLookupName(artist.name);
      return [
        [normalized, artist] as const,
        [normalized.replace(/^the\s+/, ''), artist] as const,
      ];
    }),
  );
  return editorialArtists.map((editorialArtist, index) => {
    const normalized = normalizeArtistLookupName(editorialArtist.name);
    const seeded =
      seededByName.get(normalized) ??
      seededByName.get(normalized.replace(/^the\s+/, ''));
    return seeded
      ? {
          ...editorialArtist,
          ...seeded,
          position: index + 1,
          why: editorialArtist.why,
          note: editorialArtist.note ?? seeded.note,
          isEditorialFallback: false,
          isArtistLinked: seeded.id !== null,
        }
      : editorialArtist;
  });
}

