export type GenreRule = {
  keyword: string;
  macro_slug: string;
  priority: number;
};

export type GenreFilter = 'all' | 'seen' | 'unseen';

export function isGenrePageSlug(value: string): value is MacroGenre {
  return (
    Object.prototype.hasOwnProperty.call(MACRO_GENRES, value) &&
    value !== 'other' &&
    value !== 'unclassified' &&
    Object.prototype.hasOwnProperty.call(contents, value)
  );
}

export function getGenreContent(slug: string): GenreEditorialContent | null {
  return isGenrePageSlug(slug)
    ? contents[slug]
    : (subGenreContents[slug] ?? null);
}

export function getSubGenreContent(slug: string): GenreEditorialContent | null {
  return subGenreContents[slug] ?? null;
}

export function normalizeGenreTag(value: string): string {
  return value
    .trim()
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[_-]+/g, ' ')
    .replace(/[^a-z0-9 ]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

export function resolveGenreParentFromRules(
  value: string,
  rules: GenreRule[],
): MacroGenre | null {
  const normalized = normalizeGenreTag(value);
  if (!normalized) return null;
  const directSlug = normalized.replaceAll(' ', '_');
  if (isGenrePageSlug(directSlug)) return directSlug;
  const matchingRules = rules
    .map((rule) => ({
      ...rule,
      keyword: normalizeGenreTag(rule.keyword),
    }))
    .filter(
      (rule) =>
        normalized === rule.keyword ||
        ` ${normalized} `.includes(` ${rule.keyword} `) ||
        normalized.includes(rule.keyword),
    )
    .sort(
      (left, right) =>
        right.keyword.length - left.keyword.length ||
        right.priority - left.priority,
    );
  const resolved = matchingRules.find((rule) =>
    isGenrePageSlug(rule.macro_slug),
  );
  return resolved && isGenrePageSlug(resolved.macro_slug)
    ? resolved.macro_slug
    : null;
}

export async function resolveGenreParent(
  value: string,
): Promise<string | null> {
  const normalized = normalizeGenreTag(value);
  if (!normalized) return null;
  const directSlug = normalized.replaceAll(' ', '_');
  if (isGenrePageSlug(directSlug)) return directSlug;
  const { data, error } = await supabase
    .from('genre_rules')
    .select('keyword, macro_slug, priority')
    .order('priority', { ascending: false });
  if (error) throw new Error(error.message);
  return resolveGenreParentFromRules(normalized, data ?? []);
}

export function filterGenreArtists<T extends Pick<GenreArtist, 'seen_count'>>(
  artists: T[],
  filter: GenreFilter,
): T[] {
  return artists.filter((artist) =>
    filter === 'seen'
      ? artist.seen_count > 0
      : filter === 'unseen'
        ? artist.seen_count === 0
        : true,
  );
}

export function calculateGenreProgress(
  seenCount: number,
  totalFeatures: number,
) {
  return Math.min(Math.max(0, seenCount), Math.max(0, totalFeatures));
}

