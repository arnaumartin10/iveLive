function objectValue(value: unknown): Record<string, unknown> | null {
  return typeof value === 'object' && value !== null && !Array.isArray(value)
    ? (value as Record<string, unknown>)
    : null;
}

function requiredString(value: unknown, field: string): string {
  if (typeof value !== 'string') {
    throw new Error(`Genre page field "${field}" was invalid.`);
  }
  return value;
}

function nullableString(value: unknown, field: string): string | null {
  if (value === null || typeof value === 'string') return value;
  throw new Error(`Genre page field "${field}" was invalid.`);
}

function finiteNumber(value: unknown, field: string): number {
  if (typeof value !== 'number' || !Number.isFinite(value)) {
    throw new Error(`Genre page field "${field}" was invalid.`);
  }
  return value;
}

function parseHistory(value: unknown): GenreEra[] {
  if (!Array.isArray(value)) {
    throw new Error('Genre page history was invalid.');
  }
  return value.map((entry) => {
    const era = objectValue(entry);
    if (!era) throw new Error('Genre page history entry was invalid.');
    return {
      years: requiredString(era.years, 'history.years'),
      heading: requiredString(era.heading, 'history.heading'),
      text: requiredString(era.text, 'history.text'),
    };
  });
}

function parseGenreArtist(value: unknown): GenreArtist {
  const artist = objectValue(value);
  if (!artist) throw new Error('Genre page artist entry was invalid.');
  if (typeof artist.in_wishlist !== 'boolean') {
    throw new Error('Genre page artist wishlist flag was invalid.');
  }
  const id =
    artist.id === null
      ? null
      : requiredString(artist.id, 'artist.id');
  return {
    id,
    name: requiredString(artist.name, 'artist.name'),
    image_url_thumb: nullableString(
      artist.image_url_thumb,
      'artist.image_url_thumb',
    ),
    image_url_large: nullableString(
      artist.image_url_large,
      'artist.image_url_large',
    ),
    primary_macro: nullableString(artist.primary_macro, 'artist.primary_macro'),
    position: finiteNumber(artist.position, 'artist.position'),
    why:
      artist.why === undefined
        ? undefined
        : requiredString(artist.why, 'artist.why'),
    note:
      artist.note === undefined
        ? null
        : nullableString(artist.note, 'artist.note'),
    seen_count: finiteNumber(artist.seen_count, 'artist.seen_count'),
    in_wishlist: artist.in_wishlist,
    isArtistLinked: id !== null,
    catalogQueueId:
      artist.catalog_queue_id === undefined
        ? null
        : nullableString(artist.catalog_queue_id, 'artist.catalog_queue_id'),
    catalogStatus:
      artist.catalog_status === undefined
        ? null
        : nullableString(artist.catalog_status, 'artist.catalog_status'),
  };
}

function parseArtistList(value: unknown, field: string): GenreArtist[] {
  if (!Array.isArray(value)) {
    throw new Error(`Genre page ${field} list was invalid.`);
  }
  return value.map(parseGenreArtist);
}

async function fetchEditorialArtistProfiles(
  content: GenreEditorialContent | null,
): Promise<{ pillars: GenreArtist[]; examples: GenreArtist[] }> {
  if (!content) return { pillars: [], examples: [] };

  const editorialArtists = [...content.pillars, ...content.examples];
  const normalizedNames = new Set<string>();
  for (const artist of editorialArtists) {
    const normalized = artist.name
      .normalize('NFD')
      .replace(/[\u0300-\u036f]/g, '')
      .toLowerCase()
      .trim();
    normalizedNames.add(normalized);
    normalizedNames.add(normalized.replace(/^the\s+/, ''));
  }

  const { data, error } = await supabase
    .from('artists')
    .select('id,name,image_url_thumb,image_url_large,primary_macro')
    .in('name_normalized', [...normalizedNames]);
  if (error) throw new Error(`Genre artist profiles: ${error.message}`);

  const profiles = data ?? [];
  const artistIds = profiles.map((artist) => artist.id);
  if (!artistIds.length) return getEditorialArtistFallbacks(content);

  const { data: overrides, error: overridesError } = await supabase
    .from('user_artist_image_overrides')
    .select('artist_id,profile_image_url')
    .in('artist_id', artistIds);
  if (overridesError) {
    throw new Error(`Genre artist profile photos: ${overridesError.message}`);
  }
  const profileImageByArtist = new Map(
    (overrides ?? []).flatMap((override) =>
      override.profile_image_url
        ? [[override.artist_id, override.profile_image_url] as const]
        : [],
    ),
  );
  const profilesWithOverrides = profiles.map((artist) => {
    const profileImage = profileImageByArtist.get(artist.id);
    return profileImage
      ? {
          ...artist,
          image_url_thumb: profileImage,
          image_url_large: profileImage,
        }
      : artist;
  });

  return getEditorialArtistFallbacks(content, profilesWithOverrides);
}

export async function fetchGenrePage(slug: string): Promise<GenrePageData> {
  const editorial = getGenreContent(slug);
  const response = editorial
    ? await supabase.rpc('get_genre_page', { p_slug: slug })
    : await supabase.functions.invoke('genre-autopage', {
        body: { slug },
      });
  const { data, error } = response;
  if (error) throw new Error(error.message);
  if (!data || typeof data !== 'object' || Array.isArray(data)) {
    throw new Error('Genre page response was not valid.');
  }
  const result = objectValue(data);
  if (!result || typeof result.found !== 'boolean') {
    throw new Error('Genre page response was not valid.');
  }
  const editorialProfiles = await fetchEditorialArtistProfiles(editorial);
  if (!result.found) {
    return {
      found: false,
      error: typeof result.error === 'string' ? result.error : 'not_found',
      pillars: editorialProfiles.pillars,
      examples: editorialProfiles.examples,
      viewer: {
        shows: 0,
        unique_artists: 0,
        average_rating: null,
        most_seen_artist: null,
        seen_feature_count: 0,
      },
    };
  }
  const page = objectValue(result.page);
  const viewer = objectValue(result.viewer);
  if (!page || !viewer) throw new Error('Genre page response was incomplete.');
  const mostSeen = viewer.most_seen_artist
    ? objectValue(viewer.most_seen_artist)
    : null;
  if (
    viewer.average_rating !== null &&
    typeof viewer.average_rating !== 'number'
  ) {
    throw new Error('Genre page average rating was invalid.');
  }
  const seededPillars = parseArtistList(result.pillars, 'pillars');
  const seededExamples = parseArtistList(result.examples, 'examples');
  return {
    found: true,
    page: {
      slug: requiredString(page.slug, 'page.slug'),
      title: requiredString(page.title, 'page.title'),
      tagline: requiredString(page.tagline, 'page.tagline'),
      summary: requiredString(page.summary, 'page.summary'),
      origin_place: requiredString(page.origin_place, 'page.origin_place'),
      origin_years: requiredString(page.origin_years, 'page.origin_years'),
      history: parseHistory(page.history),
      related_slugs: Array.isArray(page.related_slugs)
        ? page.related_slugs.map((related) =>
            requiredString(related, 'page.related_slugs'),
          )
        : (() => {
            throw new Error('Genre page related genres were invalid.');
          })(),
      wikipedia_title: nullableString(
        page.wikipedia_title,
        'page.wikipedia_title',
      ),
      content_version: finiteNumber(
        page.content_version,
        'page.content_version',
      ),
      reviewed: page.reviewed === true,
      auto_generated: page.auto_generated === true,
      summary_source:
        page.summary_source === 'wikipedia' || page.summary_source === 'lastfm'
          ? page.summary_source
          : null,
      summary_url: nullableString(page.summary_url ?? null, 'page.summary_url'),
      lastfm_url: nullableString(page.lastfm_url ?? null, 'page.lastfm_url'),
      wikipedia_attribution: nullableString(
        page.wikipedia_attribution ?? null,
        'page.wikipedia_attribution',
      ),
    },
    pillars: mergeEditorialArtists(editorialProfiles.pillars, seededPillars),
    examples: mergeEditorialArtists(editorialProfiles.examples, seededExamples),
    viewer: {
      shows: finiteNumber(viewer.shows, 'viewer.shows'),
      unique_artists: finiteNumber(
        viewer.unique_artists,
        'viewer.unique_artists',
      ),
      average_rating: viewer.average_rating,
      most_seen_artist: mostSeen
        ? {
            id: requiredString(mostSeen.id, 'viewer.most_seen_artist.id'),
            name: requiredString(mostSeen.name, 'viewer.most_seen_artist.name'),
            seen_count: finiteNumber(
              mostSeen.seen_count,
              'viewer.most_seen_artist.seen_count',
            ),
          }
        : null,
      seen_feature_count: finiteNumber(
        viewer.seen_feature_count,
        'viewer.seen_feature_count',
      ),
    },
  };
}
